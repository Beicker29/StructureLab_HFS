@pytest.mark.parametrize("consumer", [_available_axial_strength, _bare_steel_compression_capacity_k_n])
@pytest.mark.parametrize("bad", ["slender", "missing_cw", "offset"])
def test_h_i_axial_consumers_use_the_same_guard(consumer, bad):
    c = case(factors=dict(ya=200) if bad == "offset" else {})
    s = symmetric(type="RECTANGULAR_HSS", b_tdes_ratio=70 if bad == "slender" else 10,
                  h_tdes_ratio=10, Cw=None if bad == "missing_cw" else 0)
    with pytest.raises((RuleNotImplementedError, IncompleteSectionDataError)) as caught:
        consumer(c, s)
    assert caught.value.code in {"COMPRESSION_DOMAIN_BLOCKED", "COMPRESSION_DATA_INCOMPLETE"}
    assert caught.value.details["rule_id"] == "E4"


