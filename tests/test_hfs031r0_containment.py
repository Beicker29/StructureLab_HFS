"""Containment assertions and preserved HFS-031 independent numerical oracles.

No blocked result is credited as a corrected capacity. Expected numbers are
read from the unchanged Decimal bank, not generated by production functions.
"""
import json
import math
from pathlib import Path

import pytest

from steel_design.codes.aisc_360_22 import axial_calc
from steel_design.domain.errors import IncompleteSectionDataError, RuleNotImplementedError, ValidationError
from steel_design.domain.rules.axial_rules import AxialE3Rule, AxialE4Rule, AxialE5Rule, AxialE7Rule
from steel_design.domain.rules.combined_hss_rules import _available_axial_strength, CombinedH1HssRule
from steel_design.domain.rules.composite_rules import _bare_steel_compression_capacity_k_n
from steel_design.engine import SteelDesignEngine
from steel_design.models import SteelCase
from steel_design.sections.models import Section
from steel_design.sections.repository import SectionRepository
from steel_design.tracing import capture_trace

BANK = json.loads((Path(__file__).parent / "fixtures/hfs031/oracles.json").read_text(encoding="utf-8"))["cases"]
METHODS = ["LRFD", "ASD"]


def case(method="LRFD", **changes):
    data = dict(section_name="audit", design_method=method, loads=dict(Pu=1),
                material=dict(Fy=345, Fu=450), lengths=dict(Lx=1000, Ly=1000, Lz=6000, Lb=1000),
                connection=dict(angle_compression_mode="one_leg"))
    data.update(changes)
    return SteelCase(**data)


def symmetric(**changes):
    o = BANK["E4-symmetric"]
    data = dict(name="audit", type="W", A=float(o["A"]), Ix=float(o["Ix"]), Iy=float(o["Iy"]),
                J=float(o["J"]), Cw=float(o["Cw"]), rx=100, ry=math.sqrt(2000),
                bf_2tf_ratio=5, h_tw_ratio=20)
    data.update(changes)
    return Section(**data)


def execute(c, s):
    repository = SectionRepository()
    repository.load([s])
    return SteelDesignEngine(repository).run(c)


@pytest.mark.parametrize("method", METHODS)
def test_verified_double_symmetric_e4_preserves_independent_oracle(method):
    result = AxialE4Rule().check(case(method), symmetric())
    o = BANK["E4-symmetric"]
    assert result.capacity == pytest.approx(float(o[method+"_kN"]), rel=1e-10, abs=1e-8)
    assert result.details["memory"]["intermediate"]["pn_n"] == pytest.approx(float(o["Pn_N"]), rel=1e-10)
    assert result.details["memory"]["design_factor"]["design_method"] == method


@pytest.mark.parametrize("method", METHODS)
@pytest.mark.parametrize("axis", ["x", "y"])
def test_offset_oracle_domain_has_no_e4_result_or_trace_capacity(method, axis):
    o = BANK["E4-offset-"+axis]
    c = case(method, factors={axis+"a": float(o["offset"])}, loads=dict(Pu=float(o[method+"_kN"])*1.01))
    with capture_trace() as captured, pytest.raises(RuleNotImplementedError) as caught:
        AxialE4Rule().check(c, symmetric())
    assert caught.value.code == "COMPRESSION_DOMAIN_BLOCKED"
    assert caught.value.details["findings"] == ["F-47"]
    event, = captured.snapshot().evaluations
    assert event.outcome == "BLOCKED" and not event.check_values and not event.steps
    result = execute(c, symmetric())
    assert result.status.value == "INCOMPLETE"
    assert not any(check.clause.startswith("E4") for check in result.checks)
    assert any(check.clause == "E3-1" for check in result.checks)  # Independent, justified local mode survives.


@pytest.mark.parametrize("method", METHODS)
@pytest.mark.parametrize("h", [None, 0, 1.01])
def test_channel_unknown_or_invalid_coupling_never_returns_a_favorable_e4(method, h):
    s = symmetric(type="CHANNEL", H=h, ro=150, b_t_ratio=5)
    c = case(method, loads=dict(Pu=float(BANK["E4-channel"][method+"_kN"])*1.05))
    with pytest.raises(IncompleteSectionDataError) as caught:
        AxialE4Rule().check(c, s)
    assert 'section.H' in caught.value.details['fields']
    if h is not None:
        with pytest.raises(ValidationError):
            execute(c, s)  # Engine rejects physically invalid supplied H earlier.
        return
    result = execute(c, s)
    assert result.status.value == "INCOMPLETE"
    assert not any(check.clause.startswith("E4") for check in result.checks)


@pytest.mark.parametrize("method", METHODS)
@pytest.mark.parametrize("family", ["SINGLE_ANGLE", "DOUBLE_ANGLE"])
@pytest.mark.parametrize("mode", ["one_leg", "both_legs"])
def test_angles_do_not_bypass_containment_via_e3(method, family, mode):
    s = symmetric(type=family, b_t_ratio=8, ro=150)
    c = case(method, connection=dict(angle_compression_mode=mode))
    for rule in (AxialE3Rule(), AxialE4Rule(), AxialE5Rule(), AxialE7Rule()):
        with pytest.raises(RuleNotImplementedError):
            rule.check(c, s)
    result = execute(c, s)
    assert result.status.value == "INCOMPLETE" and not result.checks
    assert result.coverage.evaluation_errors


@pytest.mark.parametrize("method", METHODS)
@pytest.mark.parametrize("family,ratios", [
    ("W", dict(bf_2tf_ratio=20, h_tw_ratio=75)),
    ("CHANNEL", dict(b_t_ratio=20, h_tw_ratio=75, ro=150, H=.5)),
    ("RECTANGULAR_HSS", dict(b_tdes_ratio=70, h_tdes_ratio=50)),
    ("CIRCULAR_HSS", dict(d_t_ratio=100)),
])
def test_slender_domain_cannot_return_gross_area_checks(method, family, ratios):
    s, c = symmetric(type=family, **ratios), case(method)
    for rule in (AxialE3Rule(), AxialE4Rule(), AxialE7Rule()):
        with pytest.raises(RuleNotImplementedError):
            rule.check(c, s)
    result = execute(c, s)
    assert result.status.value == "INCOMPLETE" and not result.checks
    assert not result.coverage.complete
    assert all(not o.accepted_checks for o in result.coverage.obligations)


