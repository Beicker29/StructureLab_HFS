@pytest.mark.parametrize("flange,web", [(12, 40), (26, 40), (8, 120), (8, 160),
                                       (math.nextafter(9.5, math.inf), 40)])
def test_channel_outside_f2_never_uses_i_shape_alternatives(flange, web):
    s = section(flange, web, "CHANNEL")
    with pytest.raises(RuleNotImplementedError):
        ProfileRouter.get_rules(case(Mux=1, Muy=1), s)
    result = run(s, Mux=1, Muy=1)
    assert {c.clause for c in result.checks} == {"F6-1", "F6-2"}
    assert result.status.value == "INCOMPLETE"  # F-31 remains unsupported, not solved
    assert any(e["error"]["details"].get("state") == "UNSUPPORTED" for e in result.coverage.evaluation_errors)
    assert not next(o for o in result.coverage.obligations if o.id == "F.yielding.Mux").executed_checks


