def test_rounded_geometry_in_same_class_does_not_change_supplied_boundary():
    # No epsilon is applied to the classification threshold.
    assert len(ProfileRouter.get_rules(case(Mux=1), section(9.5, bf=189.99))) == 2
    with pytest.raises(IncompleteSectionDataError):
        ProfileRouter.get_rules(case(Mux=1), section(9.5, bf=190.01))


def test_no_approximation_of_clear_web_depth_from_d_and_tf():
    result = run(section(h_tw_ratio=None, h=None), Mux=1)
    assert not result.checks  # d and tf exist, but fillets do not


@pytest.mark.parametrize("major", [1, -1])
def test_biaxial_missing_web_preserves_minor_checks_and_interaction_obligation(major):
    result = run(section(h_tw_ratio=None, h=None), Mux=major, Muy=100000)
    assert {c.clause for c in result.checks} == {"F6-1", "F6-2"}
    assert result.known_failures and result.status.value == "INCOMPLETE"
    by_id = {o.id: o for o in result.coverage.obligations}
    assert not by_id["F.yielding.Mux"].executed_checks
    assert by_id["F.yielding.Muy"].executed_checks
    assert by_id["N29.interaction"].status.value == "PENDING"


