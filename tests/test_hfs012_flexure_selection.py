@pytest.mark.parametrize("e,fy", [(1e308, 1e-308), (1e-308, 1e308)])
def test_finite_materials_cannot_overflow_or_underflow_into_compactness(e, fy):
    c = case(Mux=1)
    c = c.model_copy(update={"material": c.material.model_copy(update={"E": e, "Fy": fy})})
    with pytest.raises(IncompleteSectionDataError):
        ProfileRouter.get_rules(c, section())


def test_selected_f2_yielding_preserves_independent_lrfd_reference():
    # F2-1, F1: 0.90 * 320 N/mm2 * 500000 mm3 / 1e6 = 144 kNm.
    # Absolute tolerance 1e-9 kNm: arithmetic only, no norm boundary tolerance.
    result = run(section(), Mux=-1)
    yielding = next(c for c in result.checks if c.clause == "F2-1")
    assert yielding.capacity == pytest.approx(144, rel=0, abs=1e-9)
    assert yielding.demand == 1
