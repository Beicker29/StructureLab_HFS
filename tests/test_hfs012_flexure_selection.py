"""Independent selection oracle: S22 B4.1b cases 10/15, F2-F6.

E/Fy = 200000/320 = 625; sqrt = 25. Tabulated boundaries are
flange 9.5 / 25 and web 94 / 142.5. Expected branches are enumerated
from the scopes of F2-F5, not generated by the production classifier.
These are synthetic doubly symmetric rolled W / channel inputs, not
catalog certification or independent validation of resistance formulas.
"""
import math

import pytest
from pydantic import ValidationError as PydanticValidationError

from src.steel_design.domain.errors import IncompleteSectionDataError, RuleNotImplementedError, ValidationError
from src.steel_design.domain.routing.profile_router import ProfileRouter, _classify_element
from src.steel_design.engine import SteelDesignEngine
from src.steel_design.models import SteelCase
from src.steel_design.sections.models import Section
from src.steel_design.sections.repository import SectionRepository


def case(**loads):
    return SteelCase(section_name="reference", material={"Fy": 320, "Fu": 450, "E": 200000},
                     loads=loads, lengths={"Lx": 1000, "Ly": 1000, "Lz": 1000, "Lb": 1000})


def section(flange=8.0, web=40.0, profile="W", **changes):
    values = dict(name="reference", type=profile, A=8000, Ix=100e6, Iy=20e6,
                  Sx=400000, Sy=100000, Zx=500000, Zy=150000, rx=100, ry=50,
                  J=200000, Cw=2e11, ho=440, d=web * 10 + 50, h=web * 10,
                  bf=flange * (10 if profile == "CHANNEL" else 20), tf=10, tw=10,
                  bf_2tf_ratio=flange / 2 if profile == "CHANNEL" else flange,
                  b_t_ratio=flange if profile == "CHANNEL" else None, h_tw_ratio=web)
    values.update(changes)
    return Section(**values)


def run(section, **loads):
    repo = SectionRepository()
    repo.load([section])
    return SteelDesignEngine(repo).run(case(**loads))


@pytest.mark.parametrize("flange,web,branch", [
    (8, 40, "F2"), (9.5, 94, "F2"),
    (math.nextafter(9.5, math.inf), 94, "F3"),
    (25, 94, "F3"), (math.nextafter(25, math.inf), 94, "F3"),
    (8, math.nextafter(94, math.inf), "F4"), (8, 142.5, "F4"),
    (8, math.nextafter(142.5, math.inf), "F5"),
    (30, 120, "F4"), (30, 160, "F5"),
    (math.nextafter(9.5, 0), math.nextafter(94, 0), "F2"),
    (8, math.nextafter(142.5, 0), "F4"),
])
def test_independent_w_branch_and_boundaries(flange, web, branch):
    rules = ProfileRouter.get_rules(case(Mux=1), section(flange, web))
    assert {type(rule).__name__[7:9] for rule in rules} == {branch}


@pytest.mark.parametrize("missing", ["flange", "web", "both"])
def test_unknown_ratio_never_selects_f2_and_keeps_coverage_pending(missing):
    changes = {}
    if missing in {"flange", "both"}:
        changes.update(bf_2tf_ratio=None, bf=None)
    if missing in {"web", "both"}:
        changes.update(h_tw_ratio=None, h=None)
    s = section(**changes)
    with pytest.raises(IncompleteSectionDataError) as caught:
        ProfileRouter.get_rules(case(Mux=1), s)
    assert caught.value.details["state"] == "MISSING"
    result = run(s, Mux=1)
    assert result.checks == [] and result.status.value == "INCOMPLETE"
    assert result.coverage.evaluation_errors
    pending = next(o for o in result.coverage.obligations if o.id == "N11.conditions.Mux")
    assert pending.status.value == "PENDING" and pending.applicability == "UNKNOWN"
    assert "Selection blocked" in pending.reason


@pytest.mark.parametrize("changes", [dict(bf_2tf_ratio=None), dict(h_tw_ratio=None),
                                     dict(bf_2tf_ratio=None, h_tw_ratio=None)])
def test_missing_but_derivable_compact_ratios(changes):
    s = section(**changes)
    original = s.model_dump()
    result = run(s, Mux=1)
    assert {c.clause for c in result.checks} == {"F2-1", "F2-2"}
    assert not result.coverage.evaluation_errors
    assert s.model_dump() == original  # no catalog/model enrichment
    assert result.status.value == "INCOMPLETE"  # F1/validation not discharged


@pytest.mark.parametrize("field", ["bf_2tf_ratio", "h_tw_ratio"])
@pytest.mark.parametrize("value", [0, -1, math.nan, math.inf, -math.inf, True, "8"])
def test_invalid_ratio_is_not_replaced_by_valid_geometry(field, value):
    s = section().model_copy(update={field: value})
    with pytest.raises(IncompleteSectionDataError) as caught:
        ProfileRouter.get_rules(case(Mux=1), s)
    assert caught.value.details["state"] == "INVALID"
    with pytest.raises((ValidationError, PydanticValidationError)):
        run(s, Mux=1)  # canonical HFS-011 rejects invalid input before routing


