"""Chapter E: catalog profiles vs independent hand calculations, selection and blocks.

Expected values come from tests/fixtures/chapter_e/reference.json, generated by
tests/oracles/chapter_e.py (Decimal, written from a360-22w.pdf, no product import).
"""
import json
import math

import pytest

from steel_design.codes.aisc_360_22 import compression as eq
from steel_design.domain.compression import compression_strength
from steel_design.domain.errors import IncompleteSectionDataError, RuleNotImplementedError
from steel_design.models import SteelCase

from conftest import ROOT
REFERENCE = json.loads((ROOT / "tests/fixtures/chapter_e/reference.json").read_text(encoding="utf-8"))["cases"]
REL = 1e-9  # float vs 50-digit Decimal of the same closed-form expressions


def make_case(name, Fy=345, Lx=3000, Ly=None, Lz=None, method="LRFD", xa=0, ya=0, e5=None, E=200000, Pu=100):
    return SteelCase(section_name=name, design_method=method, material={"Fy": Fy, "E": E}, Pu=Pu,
                     lengths={"Lx": Lx, "Ly": Ly or Lx, "Lz": Lz or Lx}, factors={"xa": xa, "ya": ya},
                     single_angle_e5=e5)


def e5_basis(configuration, leg, L, **overrides):
    basis = {"configuration": configuration, "connected_leg": leg, "L": L,
             "loaded_at_ends_through_same_leg": True, "welded_or_two_bolts_min": True,
             "no_intermediate_transverse_loads": True}
    return {**basis, **overrides}


def reference_case(ref, method):
    e5 = ref["e5"]
    return make_case(ref["section"], Fy=float(ref["Fy"]), Lx=float(ref["Lx"]), Ly=float(ref["Ly"]),
                     Lz=float(ref["Lz"]), ya=float(ref["ya"]), method=method,
                     e5=e5_basis(e5[0], e5[1], float(e5[2])) if e5 else None)


@pytest.mark.parametrize("method", ["LRFD", "ASD"])
@pytest.mark.parametrize("case_id", sorted(REFERENCE))
def test_catalog_profiles_match_independent_calculation(sections, case_id, method):
    ref = REFERENCE[case_id]
    result = compression_strength(reference_case(ref, method), sections[ref["section"]])
    assert result["family"] == ref["family"]
    assert result["classification"]["slender"] is ref["slender"]
    assert set(result["modes"]) == set(ref["modes"])
    for mode, expected in ref["modes"].items():
        actual = result["modes"][mode]
        for key, product_key in (("Fe_mpa", "Fe_mpa"), ("Fn_mpa", "Fn_mpa"), ("A_mm2", "area_mm2"), ("Pn_kN", "Pn_kN")):
            assert actual[product_key] == pytest.approx(float(expected[key]), rel=REL), (mode, key)
    assert result["governing_mode"] == ref["governing_mode"]
    assert result["Pn_kN"] == pytest.approx(float(ref["Pn_kN"]), rel=REL)
    assert result["available"]["LRFD"] == pytest.approx(float(ref["LRFD_kN"]), rel=REL)
    assert result["available"]["ASD"] == pytest.approx(float(ref["ASD_kN"]), rel=REL)
    assert result["available_kN"] == result["available"][method]


def test_reference_bank_covers_every_supported_catalog_family():
    assert {c["family"] for c in REFERENCE.values()} == {
        "W", "CHANNEL", "RECTANGULAR_HSS", "CIRCULAR_HSS", "SINGLE_ANGLE"}
    governing = {(c["family"], c["governing_mode"]) for c in REFERENCE.values()}
    assert {("W", "TB"), ("CHANNEL", "FTB"), ("CHANNEL", "FB-y")} <= governing
    assert all(any(c["family"] == f and c["slender"] for c in REFERENCE.values())
               for f in ("W", "CHANNEL", "RECTANGULAR_HSS", "CIRCULAR_HSS", "SINGLE_ANGLE"))


# --- Selection (Table User Note E1.1 checked against E3-E7) ---------------------------

def test_selection_by_family(sections):
    assert compression_strength(make_case("W14X90"), sections["W14X90"])["provisions"] == ["E1", "E3", "E4(a)"]
    assert compression_strength(make_case("C15X50"), sections["C15X50"])["provisions"] == ["E1", "E3", "E4(b)"]
    hss = compression_strength(make_case("PTE100X100X4MM"), sections["PTE100X100X4MM"])
    assert hss["provisions"] == ["E1", "E3"] and "E4 not applicable" in hss["notes"][0]
    slender = compression_strength(make_case("PTE120X60X2MM"), sections["PTE120X60X2MM"])
    assert slender["provisions"] == ["E1", "E3", "E7"]
    assert all(m["area_basis"] == "Ae" and m["Pn_equation"] == "E7-1" for m in slender["modes"].values())


def test_slender_section_never_uses_gross_area_when_effective_width_reduces(sections):
    result = compression_strength(make_case("PTE120X60X2MM", Lx=500), sections["PTE120X60X2MM"])
    assert all(m["area_mm2"] < sections["PTE120X60X2MM"].area for m in result["modes"].values())
    assert result["governing_equation"] == "E7-1"


def test_classification_reports_every_element(sections):
    rows = compression_strength(make_case("W8X10"), sections["W8X10"])["classification"]["elements"]
    assert [(r["element"], r["b4_case"], r["slender"]) for r in rows] == [("flange", 1, False), ("web", 5, True)]
    assert rows[1]["lambda_r"] == pytest.approx(1.49 * math.sqrt(200000 / 345))


# --- Blocks: missing data or decisions never produce a strength -----------------------

@pytest.mark.parametrize("name, kwargs, error", [
    ("PTE100X100X4MM", {"Lz": 6000}, IncompleteSectionDataError),        # E4 required, Cw absent
    ("C15X50", {"ya": 50}, RuleNotImplementedError),                     # E4(f)
    ("PTE100X100X4MM", {"xa": 10}, RuleNotImplementedError),             # E4(f)
    ("W14X90", {"xa": 10, "ya": 10}, RuleNotImplementedError),           # E4(f), both offsets
    ("2L4X4X1/4", {}, RuleNotImplementedError),                          # double angles pending
    ("L4X4X1/4", {}, RuleNotImplementedError),                           # no E5 basis -> Chapter H
    ("W14X90", {"E": 210000}, IncompleteSectionDataError),               # E defined as 200000 MPa
])
def test_unsupported_domains_are_blocked(sections, name, kwargs, error):
    with pytest.raises(error):
        compression_strength(make_case(name, **kwargs), sections[name])


@pytest.mark.parametrize("overrides", [
    {"loaded_at_ends_through_same_leg": False}, {"welded_or_two_bolts_min": False},
    {"no_intermediate_transverse_loads": False}, {"L": 10000},           # E5(4): Lc/r > 200
])
def test_single_angle_outside_e5_is_blocked(sections, overrides):
    with pytest.raises(RuleNotImplementedError):
        compression_strength(make_case("L4X4X1/4", e5={**e5_basis("a", "long", 2000), **overrides}),
                             sections["L4X4X1/4"])


def test_single_angle_requiring_e4_is_blocked(sections):
    # b/t = 16 > 0.71*sqrt(E/Fy) = 14.97 at Fy = 450 MPa: E5 requires E4 flexural-torsional buckling.
    with pytest.raises(RuleNotImplementedError, match="0.71"):
        compression_strength(make_case("L4X4X1/4", Fy=450, e5=e5_basis("a", "long", 2000)), sections["L4X4X1/4"])


def test_engine_reports_governing_capacity_and_status(engine):
    result = engine.run(make_case("W14X90", Pu=1000))
    assert result.capacity_kN == result.compression["available_kN"]
    assert result.ratio == 1000 / result.capacity_kN and result.status.value == "PASS"
    assert all(o.satisfied_by for o in result.obligations)
    assert engine.run(make_case("W14X90", Pu=10000)).status.value == "FAIL"


def test_engine_blocked_compression_is_incomplete(engine):
    result = engine.run(make_case("2L4X4X1/4", Pu=10))
    assert result.status.value == "INCOMPLETE" and result.capacity_kN is None and result.errors


# --- Formula properties (independent of the catalog) ---------------------------------

def test_e3_branches_are_continuous_at_fy_over_fe_2_25():
    fe = 345 / 2.25
    assert eq.nominal_stress(345, fe)["equation"] == "E3-2"
    assert eq.nominal_stress(345, fe * (1 - 1e-12))["Fn_mpa"] == pytest.approx(0.877 * fe, rel=1e-3)


def test_e7_c2_matches_table_e7_1_rounded_values():
    for kind, c2 in (("STIFFENED", 1.31), ("HSS_WALL", 1.38), ("UNSTIFFENED", 1.49)):
        row = eq.e7_effective_width(b=100, t=1, lambda_r=30, Fn=345, Fy=345, kind=kind)
        assert round(row["c2"], 2) == c2


def test_e4_4_reduces_to_e4_3_for_a_symmetry_axis():
    fey, fez, ro, yo = 300.0, 250.0, 100.0, 60.0
    h = 1 - (yo / ro) ** 2
    cubic = eq.flexural_torsional_stress_unsymmetric(Fex=1e6, Fey=fey, Fez=fez, xo=0.0, yo=yo, ro=ro)
    assert cubic["Fe_mpa"] == pytest.approx(eq.flexural_torsional_stress_singly_symmetric(fey, fez, h), rel=1e-12)


@pytest.mark.parametrize("configuration, s", [("a", 80), ("b", 75)])
def test_e5_branches_are_continuous(configuration, s):
    below = eq.e5_effective_slenderness(L_over_ra=s, configuration=configuration, connected_leg="long",
                                        leg_ratio=1, L_over_rz=s)
    above = eq.e5_effective_slenderness(L_over_ra=s + 1e-9, configuration=configuration, connected_leg="long",
                                        leg_ratio=1, L_over_rz=s)
    assert below["Lc_over_r"] == pytest.approx(above["Lc_over_r"], abs=1e-6)


def test_e6_modified_slenderness():
    assert eq.e6_modified_slenderness(Lc_over_r_o=80, a_over_ri=60, connector="snug_tight", Ki=0.5)["Lc_over_r_m"] == 100
    assert eq.e6_modified_slenderness(Lc_over_r_o=80, a_over_ri=40, connector="welded", Ki=0.5)["equation"] == "E6-2a"
    assert eq.e6_modified_slenderness(Lc_over_r_o=80, a_over_ri=120, connector="welded", Ki=0.5)["Lc_over_r_m"] == 100


def test_round_hss_area_bounded_and_upper_limit():
    near = eq.e7_round_hss_area(Ag=1000, D_over_t=0.112 * 200000 / 345, E=200000, Fy=345)
    assert near["bounded_to_Ag"] and near["Ae_mm2"] == 1000 and near["Ae_equation_mm2"] > 1000
    with pytest.raises(ValueError):
        eq.e7_round_hss_area(Ag=1000, D_over_t=0.45 * 200000 / 345, E=200000, Fy=345)
